import assert from 'node:assert/strict';
import { HOME_PANELS } from '../src/data/homePanels';
import { normalizeHomeDesign, DEFAULT_HOME_DESIGN, saveHomeDesign, adoptHomeDesign, HOME_DESIGN_KEY } from '../src/hooks/useHomeDesign';
const defaults=normalizeHomeDesign(null);
assert.deepEqual(defaults,DEFAULT_HOME_DESIGN);
const custom=normalizeHomeDesign({layout:'right',columns:2,spacing:'compact',order:['ownedLibrary','welcome','ownedLibrary','unknown'],updatedAt:123});
assert.deepEqual(custom.order.slice(0,2),['ownedLibrary','welcome']);
assert.equal(new Set(custom.order).size, HOME_PANELS.length);
assert.equal(custom.order.length,HOME_PANELS.length);
assert.equal(custom.layout,'right');assert.equal(custom.columns,2);assert.equal(custom.updatedAt,123);
const invalid=normalizeHomeDesign({layout:'invalid',columns:999,spacing:'invalid',order:'bad',updatedAt:Infinity});
assert.deepEqual(invalid,defaults);
assert.ok(custom.order.includes('recentCommunity'),'new panels added to old layouts');
const storage=new Map<string,string>();
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(key:string)=>storage.get(key)??null,setItem:(key:string,value:string)=>storage.set(key,value)}});
Object.defineProperty(globalThis,'window',{configurable:true,value:new EventTarget()});
saveHomeDesign({...defaults,updatedAt:10});
adoptHomeDesign({...custom,updatedAt:20});
assert.equal(JSON.parse(storage.get(HOME_DESIGN_KEY)!).layout,'right','newer cloud layout adopted');
adoptHomeDesign({...defaults,updatedAt:5});
assert.equal(JSON.parse(storage.get(HOME_DESIGN_KEY)!).updatedAt,20,'older snapshot does not replace local changes');
console.log('Home design tests passed: defaults, normalization, deduplication, layouts, new-panel migration and cloud adoption.');
