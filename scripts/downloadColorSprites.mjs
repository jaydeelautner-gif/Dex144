// Downloads and appends the cosmetic colour/coat form sprites (Vivillon wing
// patterns, Alcremie creams, Furfrou trims, flower colours…) to public/sprites.bin.
//
// PokeAPI publishes these as "<dexId>-<formSlug>.png" rather than under a numeric
// form id, so they are fetched by name. Appending preserves every Pokémon and item
// slice already in the binary; only colour slices are added.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const POKEAPI = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon';
const binPath = join(root, 'public/sprites.bin');
const generatedPath = join(root, 'src/data/spriteFiles.generated.ts');
const cacheDir = join(root, '.sprite-cache/colors');
const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47]);

// sprite id -> form slug, from PokeAPI's form table.
const csv = await (await fetch('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_forms.csv')).text();
const formsBySprite = new Map();
{
  const lines = csv.trim().split(/\r?\n/);
  const header = lines.shift().split(',');
  const at = (name) => header.indexOf(name);
  for (const line of lines) {
    const cells = line.split(',');
    if (cells[at('is_default')] === '1') continue;
    const slug = cells[at('identifier')];
    formsBySprite.set(Number(cells[at('id')]), slug.slice(slug.split('-')[0].length + 1));
  }
}

const colorTable = readFileSync(join(root, 'src/data/colorVariants.generated.ts'), 'utf8');
const wanted = [];
for (const match of colorTable.matchAll(/"(\d+)":(\[[^\]]*\])/g)) {
  const dexId = Number(match[1]);
  for (const entry of JSON.parse(match[2])) {
    const form = formsBySprite.get(entry.spriteId);
    if (form) wanted.push({ dexId, form, spriteId: entry.spriteId });
  }
}
if (wanted.length < 150) throw Error(`Only ${wanted.length} colour forms found.`);

mkdirSync(cacheDir, { recursive: true });
let saved = 0, missing = 0;
let cursor = 0;
async function worker() {
  while (cursor < wanted.length) {
    const { dexId, form } = wanted[cursor++];
    for (const folder of ['', 'shiny/']) {
      const rel = `${dexId}-${form}.png`;
      const file = join(cacheDir, folder === '' ? rel : `shiny-${rel}`);
      if (existsSync(file) && statSync(file).size > 0) continue;
      try {
        const res = await fetch(`${POKEAPI}/${folder}${rel}`, { signal: AbortSignal.timeout(20000) });
        if (!res.ok) { missing++; continue; }
        const bytes = Buffer.from(await res.arrayBuffer());
        if (!bytes.subarray(0, 4).equals(PNG_MAGIC)) { missing++; continue; }
        writeFileSync(file, bytes);
        saved++;
      } catch { missing++; }
    }
  }
}
await Promise.all(Array.from({ length: 10 }, worker));

const source = readFileSync(generatedPath, 'utf8');
const readMap = (name) => JSON.parse(source.match(new RegExp(`export const ${name}[^=]*= (\\{[\\s\\S]*?\\});\\n`))[1]);
const spriteFiles = readMap('SPRITE_FILES');
const formId = readMap('FORM_ID_SPRITE_FILES');
const formFiles = readMap('FORM_SPRITE_FILES');
const female = readMap('FEMALE_SPRITE_FILES');
const items = readMap('ITEM_SPRITE_SLICES');

let end = 0;
for (const map of [spriteFiles, formId, formFiles, female, items]) {
  for (const value of Object.values(map)) {
    for (const slice of typeof value === 'object' && value && 'o' in value ? [value] : Object.values(value ?? {})) {
      if (slice && typeof slice === 'object' && 'o' in slice) end = Math.max(end, slice.o + slice.l);
    }
  }
}
const size = statSync(binPath).size;
if (end > size) throw Error(`Sprite index (${end}) exceeds the binary (${size}); rebuild instead.`);

const chunks = [];
const slices = {};
let offset = size;
for (const { dexId, form, spriteId } of wanted) {
  for (const [folder, key] of [['', 'normal'], ['shiny/', 'shiny']]) {
    const rel = `${dexId}-${form}.png`;
    const file = join(cacheDir, folder === '' ? rel : `shiny-${rel}`);
    if (!existsSync(file)) continue;
    const bytes = readFileSync(file);
    chunks.push(bytes);
    (slices[spriteId] ??= {})[key] = { o: offset, l: bytes.length };
    offset += bytes.length;
  }
}
if (!chunks.length) throw Error('No colour sprites to append.');
writeFileSync(binPath, Buffer.concat([readFileSync(binPath), ...chunks]));
writeFileSync(
  generatedPath,
  [
    '// Generated by scripts/downloadSprites.ts + scripts/appendItemSprites.mjs + scripts/downloadColorSprites.mjs.',
    '// Sprites live in one binary file; each entry is a byte slice of /sprites.bin.',
    'export interface SpriteSlice { o: number; l: number }',
    `export const SPRITE_BLOB = '/sprites.bin';`,
    `export const SPRITE_FILES: Record<number, { normal: SpriteSlice; shiny: SpriteSlice }> = ${JSON.stringify(spriteFiles)};`,
    `export const FORM_ID_SPRITE_FILES: Record<number, { normal?: SpriteSlice; shiny?: SpriteSlice }> = ${JSON.stringify(formId)};`,
    `export const FORM_SPRITE_FILES: Record<string, SpriteSlice> = ${JSON.stringify(formFiles)};`,
    `export const FEMALE_SPRITE_FILES: Record<number, SpriteSlice> = ${JSON.stringify(female)};`,
    `export const ITEM_SPRITE_SLICES: Record<string, SpriteSlice> = ${JSON.stringify(items)};`,
    `export const COLOR_SPRITE_FILES: Record<number, { normal?: SpriteSlice; shiny?: SpriteSlice }> = ${JSON.stringify(slices)};`,
    '',
  ].join('\n'),
);
console.log(`Colour sprites: ${saved} files saved, ${missing} unavailable; ${Object.keys(slices).length} forms bundled. sprites.bin is ${(offset / 1048576).toFixed(1)} MB.`);
