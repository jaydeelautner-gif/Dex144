// Compact offline species breeding data from PokéAPI's canonical CSV tables.
// Three downloads instead of 1,025 individual API requests. No runtime API use.
import { writeFileSync, renameSync } from 'node:fs';
const root=new URL('../',import.meta.url);
const source='https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/';
async function table(name){
  const response=await fetch(source+name+'.csv',{signal:AbortSignal.timeout(30000)});
  if(!response.ok)throw Error(`${name}: HTTP ${response.status}`);
  const lines=(await response.text()).trim().split(/\r?\n/);
  const header=lines.shift().split(',');
  return lines.map(line=>Object.fromEntries(line.split(',').map((value,i)=>[header[i],value])));
}
const [species,eggRows,groupRows]=await Promise.all([table('pokemon_species'),table('pokemon_egg_groups'),table('egg_groups')]);
const groups=Object.fromEntries(groupRows.map(row=>[Number(row.id),row.identifier]));
const rows={};
for(const row of species){
  const id=Number(row.id);if(id<1||id>1025)continue;
  const entry={generation:Number(row.generation_id),parent:row.evolves_from_species_id?Number(row.evolves_from_species_id):null,baby:row.is_baby==='1',genderRate:Number(row.gender_rate),hatchCycles:Number(row.hatch_counter),groups:eggRows.filter(egg=>Number(egg.species_id)===id).map(egg=>Number(egg.egg_group_id))};
  if(!entry.groups.length || entry.groups.some(group=>!groups[group]) || !Number.isInteger(entry.hatchCycles) || entry.hatchCycles<0 || !Number.isInteger(entry.generation) || entry.generation<1 || entry.generation>9 || entry.genderRate< -1 || entry.genderRate>8)throw Error(`Invalid breeding data for #${id}`);
  rows[id]=entry;
}
if(Object.keys(rows).length!==1025)throw Error('Incomplete breeding data; the previous file was not replaced.');
for(const [id,entry] of Object.entries(rows))if(entry.parent && !rows[entry.parent])throw Error(`Unknown parent for #${id}`);
const output=new URL('src/data/breeding.generated.ts',root);
const text=`// Generated by scripts/generateBreedingData.mjs from PokéAPI CSVs.\n// https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv\nexport interface BreedingSpecies { generation:number; parent:number|null; baby:boolean; genderRate:number; hatchCycles:number; groups:number[] }\nexport const EGG_GROUPS:Record<number,string> = ${JSON.stringify(groups)};\nexport const BREEDING_SPECIES:Record<number,BreedingSpecies> = ${JSON.stringify(rows)};\n`;
writeFileSync(new URL(output.href+'.tmp'),text);renameSync(new URL(output.href+'.tmp'),output);
console.log(`Generated breeding data for ${Object.keys(rows).length} species and ${Object.keys(groups).length} egg groups.`);
