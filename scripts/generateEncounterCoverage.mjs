/**
 * Generate a species → games-with-encounter-coverage map from the enriched
 * bundle (PokéAPI + Serebii supplement). Used to correct the hand-curated
 * availability switch when verified encounter rows contradict an
 * "unavailable" verdict (e.g. Charmander IS obtainable in Sword via the
 * Postwick gift + Max Raid dens).
 *
 * Run:  node scripts/generateEncounterCoverage.mjs
 * Out:  src/data/encounterCoverage.generated.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const enc = JSON.parse(readFileSync(join(ROOT, 'public/data/encounters.json'), 'utf8'));

const covered = {}; // speciesId → sorted gameIds with ≥1 encounter row
for (const [pid, byGame] of Object.entries(enc)) {
  const games = Object.entries(byGame)
    .filter(([, areas]) => Object.keys(areas).length > 0)
    .map(([g]) => g)
    .sort();
  if (games.length > 0) covered[pid] = games;
}

const lines = Object.entries(covered)
  .sort((a, b) => Number(a[0]) - Number(b[0]))
  .map(([pid, games]) => `  ${pid}: [${games.map((g) => `'${g}'`).join(', ')}],`)
  .join('\n');

const out = `/**
 * AUTO-GENERATED by scripts/generateEncounterCoverage.mjs — do not edit by hand.
 *
 * Maps national dex number → game ids (canonical) in which the species has
 * verified encounter rows in public/data/encounters.json (wild, gift,
 * trade, raid…). computeAvailabilityForPokemon uses this to correct
 * hand-curated "unavailable" verdicts that the verified data contradicts.
 */
export const ENCOUNTER_COVERED_GAMES: Record<number, string[]> = {
${lines}
};
`;

const dest = join(ROOT, 'src', 'data', 'encounterCoverage.generated.ts');
writeFileSync(dest, out);
console.log(`Wrote ${dest}: ${Object.keys(covered).length} species with coverage`);
