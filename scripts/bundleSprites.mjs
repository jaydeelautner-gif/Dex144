// Packs every downloaded sprite into ONE binary file plus an offset index, so
// the repository (and hosts with a file-count limit, like Google AI Studio)
// sees two sprite files instead of ~2,800.
//
//   public/sprites.bin          concatenated PNG bytes
//   src/data/spriteFiles.generated.ts   id/form -> { o: offset, l: length }
//
// The app slices sprites.bin into blob URLs at runtime
// (see src/utils/spriteArchive.ts).
//
// Run: npm run bundle:sprites
import { readFileSync, writeFileSync, rmSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const generatedPath = join(root, 'src/data/spriteFiles.generated.ts');
const source = readFileSync(generatedPath, 'utf8');

/** Reads one exported object literal from the generated file. */
function readMap(name) {
  const m = source.match(new RegExp(`export const ${name}[^=]*= (\\{[\\s\\S]*?\\});\\n`));
  if (!m) throw new Error(`Could not read ${name} from ${generatedPath}`);
  return JSON.parse(m[1]);
}

const spriteFiles = readMap('SPRITE_FILES');
const formIdSpriteFiles = readMap('FORM_ID_SPRITE_FILES');
const formSpriteFiles = readMap('FORM_SPRITE_FILES');
const femaleSpriteFiles = readMap('FEMALE_SPRITE_FILES');

// Every local path referenced by the maps, de-duplicated.
const paths = new Set();
const collect = (value) => {
  if (typeof value === 'string') { if (value.startsWith('/sprites/')) paths.add(value); return; }
  if (value && typeof value === 'object') for (const v of Object.values(value)) collect(v);
};
[Object.values(spriteFiles), Object.values(formIdSpriteFiles), Object.values(formSpriteFiles), Object.values(femaleSpriteFiles)].forEach(collect);

const chunks = [];
const index = new Map();
let offset = 0;
for (const url of [...paths].sort()) {
  const file = join(root, '.sprite-cache', url.replace('/sprites/', ''));
  if (!existsSync(file)) continue;
  const bytes = readFileSync(file);
  chunks.push(bytes);
  index.set(url, { o: offset, l: bytes.length });
  offset += bytes.length;
}
writeFileSync(join(root, 'public/sprites.bin'), Buffer.concat(chunks));

/** Rewrites every path in a map to its { o, l } slice. */
const toSlices = (value) => {
  if (typeof value === 'string') return index.get(value) ?? null;
  return Object.fromEntries(
    Object.entries(value).map(([k, v]) => [k, toSlices(v)]).filter(([, v]) => v !== null),
  );
};
const slicesOf = (map) =>
  Object.fromEntries(Object.entries(map).map(([k, v]) => [k, toSlices(v)]).filter(([, v]) => v !== null));

// The data files reference sprites by local path, so key the form map by the
// resolved path as well as the original URL it was collected under.
const formSlices = {};
for (const [key, path] of Object.entries(formSpriteFiles)) {
  const slice = index.get(path);
  if (!slice) continue;
  formSlices[key] = slice;
  formSlices[path] = slice;
}

writeFileSync(
  generatedPath,
  [
    '// Generated by scripts/downloadSprites.ts + scripts/bundleSprites.mjs.',
    '// Sprites live in one binary file; each entry is a byte slice of /sprites.bin.',
    'export interface SpriteSlice { o: number; l: number }',
    `export const SPRITE_BLOB = '/sprites.bin';`,
    `export const SPRITE_FILES: Record<number, { normal: SpriteSlice; shiny: SpriteSlice }> = ${JSON.stringify(slicesOf(spriteFiles))};`,
    `export const FORM_ID_SPRITE_FILES: Record<number, { normal?: SpriteSlice; shiny?: SpriteSlice }> = ${JSON.stringify(slicesOf(formIdSpriteFiles))};`,
    `export const FORM_SPRITE_FILES: Record<string, SpriteSlice> = ${JSON.stringify(formSlices)};`,
    `export const FEMALE_SPRITE_FILES: Record<number, SpriteSlice> = ${JSON.stringify(slicesOf(femaleSpriteFiles))};`,
    '',
  ].join('\n'),
);

// Remove the loose files; the binary is now the only sprite asset.
if (existsSync(join(root, 'public/sprites'))) rmSync(join(root, 'public/sprites'), { recursive: true, force: true });

const binBytes = statSync(join(root, 'public/sprites.bin')).size;
console.log(`Bundled ${index.size} sprites into public/sprites.bin (${(binBytes / 1024 / 1024).toFixed(1)} MB).`);
