// Generates src/data/items.generated.ts from PokéAPI's canonical CSVs:
// every item (name/category/effect/fling + generations it appears in) and the
// full TM/HM table per version group. A dozen downloads instead of thousands of
// API calls; no runtime network use.
import { writeFileSync, renameSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const source = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/';

/** Minimal RFC4180-ish CSV parser (handles quoted fields with commas/quotes). */
function parseCsv(text) {
  const rows = []; let row = []; let field = ''; let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false; }
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { row.push(field); field = ''; }
    else if (char === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (char !== '\r') field += char;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows.filter(r => r.length === header.length).map(r => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}
async function table(name) {
  const response = await fetch(source + name + '.csv', { signal: AbortSignal.timeout(45000) });
  if (!response.ok) throw Error(`${name}: HTTP ${response.status}`);
  return parseCsv(await response.text());
}
const [items, itemNames, categories, prose, games, machines, versionGroups, moves, moveNames] = await Promise.all([
  table('items'), table('item_names'), table('item_categories'), table('item_prose'),
  table('item_game_indices'), table('machines'), table('version_groups'), table('moves'), table('move_names'),
]);
const ENGLISH = '9';
const categoryOf = Object.fromEntries(categories.map(row => [Number(row.id), row.identifier]));
const generationsByItem = new Map();
for (const row of games) {
  const id = Number(row.item_id);
  if (!generationsByItem.has(id)) generationsByItem.set(id, new Set());
  generationsByItem.get(id).add(Number(row.generation_id));
}
const englishName = new Map(itemNames.filter(row => row.local_language_id === ENGLISH).map(row => [Number(row.item_id), row.name]));

const allItems = {};
for (const row of items) {
  const id = Number(row.id);
  const name = englishName.get(id);
  if (!name || /^(TM|TR|HM)\d+$/.test(name)) continue; // machines listed separately
  const effect = prose.find(p => Number(p.item_id) === id && p.local_language_id === ENGLISH)?.short_effect ?? '';
  const generations = [...(generationsByItem.get(id) ?? [])].sort((a, b) => a - b);
  const cost = Number(row.cost) || 0;
  allItems[id] = {
    name: name.slice(0, 80),
    category: (categoryOf[Number(row.category_id)] ?? 'unknown').slice(0, 40),
    effect: effect.slice(0, 300),
    flingPower: Number(row.fling_power) || 0,
    cost,
    generations,
  };
}
const moveName = new Map(moveNames.filter(row => row.local_language_id === ENGLISH).map(row => [Number(row.move_id), row.name]));
const moveById = new Map(moves.map(row => [Number(row.id), row]));
const groupName = Object.fromEntries(versionGroups.map(row => [Number(row.id), row.identifier]));
const tms = {};
for (const row of machines) {
  const group = groupName[Number(row.version_group_id)];
  const item = englishName.get(Number(row.item_id));
  const move = moveName.get(Number(row.move_id));
  if (!group || !item || !move) continue;
  const entry = { n: Number(row.machine_number), item, move, type: moveById.get(Number(row.move_id))?.type_id ? Number(moveById.get(Number(row.move_id)).type_id) : 0 };
  (tms[group] ??= []).push(entry);
}
for (const group of Object.keys(tms)) tms[group].sort((a, b) => a.n - b.n || a.item.localeCompare(b.item));

if (Object.keys(allItems).length < 800) throw Error('Item table looks incomplete; previous file kept.');
if (Object.keys(tms).length < 10) throw Error('TM/HM table looks incomplete; previous file kept.');
const output = new URL('src/data/items.generated.ts', root);
const text = `// Generated by scripts/generateItemsData.mjs from PokéAPI CSVs. Do not edit by hand.
export interface ItemEntry { name:string; category:string; effect:string; flingPower:number; cost:number; generations:number[] }
export interface TmEntry { n:number; item:string; move:string; type:number }
export const ITEM_TYPES:Record<number,string> = ${JSON.stringify({ 1:'Normal',2:'Fighting',3:'Flying',4:'Poison',5:'Ground',6:'Rock',7:'Bug',8:'Ghost',9:'Steel',10:'Fire',11:'Water',12:'Grass',13:'Electric',14:'Psychic',15:'Ice',16:'Dragon',17:'Dark',18:'Fairy' })};
export const ITEMS:Record<number,ItemEntry> = ${JSON.stringify(allItems)};
export const TM_HM:Record<string,TmEntry[]> = ${JSON.stringify(tms)};
export const MOVE_MACHINE_GROUPS:string[] = ${JSON.stringify(Object.keys(tms).sort())};
`;
writeFileSync(new URL(output.href + '.tmp'), text);
renameSync(new URL(output.href + '.tmp'), output);
console.log(`Generated ${Object.keys(allItems).length} items and ${Object.values(tms).reduce((n, l) => n + l.length, 0)} TM/HM entries across ${Object.keys(tms).length} version groups.`);
