// Appends the downloaded item sprites to the existing public/sprites.bin and
// records their byte slices in src/data/spriteFiles.generated.ts. Appending (not
// rebuilding) keeps every Pokémon slice already used by the app valid.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const binPath = join(root, 'public/sprites.bin');
const generatedPath = join(root, 'src/data/spriteFiles.generated.ts');
const itemDir = join(root, '.sprite-cache/items');
if (!existsSync(itemDir)) throw Error('No item sprite cache. Run scripts/downloadItemSprites.mjs first.');
const source = readFileSync(generatedPath, 'utf8');
const readMap = (name) => JSON.parse(source.match(new RegExp(`export const ${name}[^=]*= (\\{[\\s\\S]*?\\});\\n`))[1]);
const spriteFiles = readMap('SPRITE_FILES');
const formId = readMap('FORM_ID_SPRITE_FILES');
const formFiles = readMap('FORM_SPRITE_FILES');
const female = readMap('FEMALE_SPRITE_FILES');

// Highest end offset already used, so appended item slices never overlap.
let end = 0;
for (const map of [spriteFiles, formId, formFiles, female]) {
  for (const value of Object.values(map)) {
    for (const slice of typeof value === 'object' && value && 'o' in value ? [value] : Object.values(value ?? {})) {
      if (slice && typeof slice === 'object' && 'o' in slice) end = Math.max(end, slice.o + slice.l);
    }
  }
}
const existing = statSync(binPath).size;
if (end > existing) throw Error(`Sprite index (${end}) exceeds the binary (${existing}); rebuild instead.`);

const chunks = [];
const slices = {};
let offset = existing;
for (const name of readdirSync(itemDir).filter((file) => file.endsWith('.png')).sort()) {
  const bytes = readFileSync(join(itemDir, name));
  chunks.push(bytes);
  slices[name.replace(/\.png$/, '')] = { o: offset, l: bytes.length };
  offset += bytes.length;
}
if (!chunks.length) throw Error('No item sprites to append.');
writeFileSync(binPath, Buffer.concat([readFileSync(binPath), ...chunks]));
writeFileSync(
  generatedPath,
  [
    '// Generated by scripts/downloadSprites.ts + scripts/appendItemSprites.mjs.',
    '// Sprites live in one binary file; each entry is a byte slice of /sprites.bin.',
    'export interface SpriteSlice { o: number; l: number }',
    `export const SPRITE_BLOB = '/sprites.bin';`,
    `export const SPRITE_FILES: Record<number, { normal: SpriteSlice; shiny: SpriteSlice }> = ${JSON.stringify(spriteFiles)};`,
    `export const FORM_ID_SPRITE_FILES: Record<number, { normal?: SpriteSlice; shiny?: SpriteSlice }> = ${JSON.stringify(formId)};`,
    `export const FORM_SPRITE_FILES: Record<string, SpriteSlice> = ${JSON.stringify(formFiles)};`,
    `export const FEMALE_SPRITE_FILES: Record<number, SpriteSlice> = ${JSON.stringify(female)};`,
    `export const ITEM_SPRITE_SLICES: Record<string, SpriteSlice> = ${JSON.stringify(slices)};`,
    '',
  ].join('\n'),
);
console.log(`Appended ${chunks.length} item sprites. sprites.bin is now ${(offset / 1024 / 1024).toFixed(1)} MB.`);
